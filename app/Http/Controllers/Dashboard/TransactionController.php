namespace App\Http\Controllers\Dashboard;

use App\Crud\TransactionCrud;
use App\Crud\TransactionsHistoryCrud;
use App\Http\Controllers\DashboardController;
use App\Models\Transaction;
use App\Models\TransactionAccount;
use App\Models\TransactionHistory;
use App\Services\DateService;
use App\Services\Options;
use App\Services\TransactionService;
use Illuminate\Http\Request;

class TransactionController extends DashboardController
{
  public function __construct(
    public TransactionService $transactionService,
    public Options $optionsService,
    protected DateService $dateService
  ) {
    // ...
  }

  public function get($id = null)
  {
    return $this->transactionService->get($id);
  }

  public function getTransactionHistory(Transaction $transaction)
  {
    return TransactionsHistoryCrud::table([
      'title' => sprintf(__('"%s" Record History'), $transaction->name),
      'description' => __('Shows all histories generated by the transaction.'),
      'queryParams' => [
        'transaction_id' => $transaction->id,
      ],
    ]);
  }

  public function saveRule(Request $request)
  {
    return $this->transactionService->saveTransactionRule($request->input('rule'));
  }

  public function listTransactions()
  {
    /**
     * The single backend-driven list shell (T4.2): the transactions table
     * renders from `TransactionCrud::table()` — the Trigger GET (with its
     * confirm) and History GOTO actions render from `$actions`. `table()`
     * enforces `allowedTo('read')` (`subul.read.transactions`) internally.
     */
    return TransactionCrud::table();
  }

  public function createTransaction()
  {
    $infoMessage = session()->get('infoMessage');

    if (! sb()->canPerformAsynchronousOperations()) {
      $infoMessage = __('Unable to use Scheduled, Recurring and Entity Transactions as Queues aren\'t configured correctly.');
    }

    if (sb()->option->get('sb_accounting_expenses_accounts') === null) {
      session()->flash('infoMessage', __('You need to configure the expense accounts before creating a transaction.'));

      return redirect()->route('sb.dashboard.settings', ['settings' => 'accounting']);
    }

    /**
     * The single backend-driven form shell (Phase 3): the transaction
     * create form renders from `TransactionCrud::form()`. The queue
     * warning (and any flashed message) travels through the config
     * overlay as `infoMessage`, which the generic shell renders as its
     * top notice banner.
     */
    return TransactionCrud::form(config: ['infoMessage' => $infoMessage]);
  }

  public function editTransaction(Transaction $transaction)
  {
    $infoMessage = session()->get('infoMessage');

    if (! sb()->canPerformAsynchronousOperations()) {
      $infoMessage = __('Unable to use Scheduled, Recurring and Entity Transactions as Queues aren\'t configured correctly.');
    }

    /**
     * Same generic form shell, pre-filled from the route-bound transaction.
     */
    return TransactionCrud::form(entry: $transaction, config: ['infoMessage' => $infoMessage]);
  }

  public function getConfigurations(Transaction $transaction)
  {
    return $this->transactionService->getConfigurations($transaction);
  }

  /**
   * Implement a transaction registration
   *
   * @param Request
   * @return json
   */
  public function post(Request $request) // <= need to add a validation
  {
    $fields = $request->only([
      'name',
      'active',
      'account_id',
      'description',
      'media_id',
      'value',
      'recurring',
      'type',
      'group_id',
      'occurrence',
      'occurrence_value',
      'scheduled_date',
    ]);

    return $this->transactionService->create($fields);
  }

  public function putTransactionAccount(Request $request, TransactionAccount $account)
  {
    $fields = $request->only([
      'name',
      'operation',
      'description',
      'account',
    ]);

    return $this->transactionService->editTransactionAccount($account, $fields);
  }

  /**
   * Implement saving an expense
   * should check the recursive hierarchy
   *
   * @param Request
   * @param int expense id
   * @return json
   */
  public function put(Request $request, $id)
  {
    $fields = $request->only([
      'name',
      'active',
      'category_id',
      'description',
      'media_id',
      'value',
      'recurring',
      'type',
      'group_id',
      'occurrence',
      'occurrence_value',
      'scheduled_date',
    ]);

    return $this->transactionService->edit($id, $fields);
  }

  public function delete(Transaction $transaction)
  {
    return $this->transactionService->deleteTransaction($transaction);
  }

  /**
   * get an expense category
   *
   * @param int|null category id
   * @return json
   */
  public function getExpensesCategories($id = null)
  {
    return $this->transactionService->getTransactionAccountByID($id);
  }

  /**
   * get all sub accounts
   *
   * @return Collection
   */
  public function getSubAccounts()
  {
    return $this->transactionService->getSubAccounts();
  }

  /**
   * get all actions
   *
   * @return Collection
   */
  public function getActions()
  {
    return $this->transactionService->getActions();
  }

  public function getRules()
  {
    return $this->transactionService->getRules();
  }

  /**
   * Delete a transaction action rule.
   */
  public function deleteRule(\App\Models\TransactionActionRule $rule)
  {
    return $this->transactionService->deleteRule($rule);
  }

  /**
   * delete a specific transaction account
   */
  public function deleteAccount(TransactionAccount $account)
  {
    return $this->transactionService->deleteTransactionAccount($account);
  }

  /**
   * Create an transaction account.
   *
   * @param Request
   * @return json
   */
  public function postTransactionsAccount(Request $request)
  {
    $fields = $request->only([
      'name',
      'operation',
      'description',
      'account',
    ]);

    return $this->transactionService->createAccount($fields);
  }

  /**
   * Get expenses entries under a specific
   * transaction account
   */
  public function getTransactionAccountsHistory(int $id): array
  {
    return $this->transactionService->getTransactionAccountByID($id)->transactions;
  }

  public function transactionsHistory()
  {
    /**
     * The single backend-driven list shell (T5.4): the history table
     * renders from `TransactionsHistoryCrud::table()` — the
     * Create-Reflection GET and Delete actions render from `$actions`
     * (both real permissions). `table()` enforces
     * `subul.read.transactions-history` internally.
     */
    return TransactionsHistoryCrud::table();
  }

  public function triggerTransaction(Transaction $transaction)
  {
    sb()->restrict(['subul.update.transactions']);

    return $this->transactionService->triggerTransaction($transaction);
  }

  public function getTransactionAccountFromCategory(Request $request)
  {
    $identifier = $request->input('identifier') ?? $request->input('category_identifier');
    return $this->transactionService->getTransactionAccountFromCategory($identifier, $request->input('exclude'));
  }

  public function resetDefaultAccounts(Request $request)
  {
    sb()->restrict(['subul.create.transactions-account']);

    return $this->transactionService->createDefaultAccounts();
  }

  public function createReflection(TransactionHistory $history)
  {
    sb()->restrict(['subul.create.transactions']);

    return $this->transactionService->reflectTransactionFromRule($history, null);
  }
}
