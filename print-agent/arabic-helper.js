/**
 * Arabic Text Helper for ESC/POS & TSPL Thermal Printers
 * Powered by `js-arabic-reshaper` for glyph shaping and `bidi-js` for bidirectional reordering.
 * Translates and encodes Arabic text for hardware printers (CP864, CP1256, UTF-8, CP437).
 */

const iconv = require('iconv-lite');
const { reshape } = require('js-arabic-reshaper');
const bidiFactory = require('bidi-js');
const bidi = bidiFactory();

/**
 * Check if text contains Arabic characters (0x0600..0x06FF, 0xFB50..0xFDFF, 0xFE70..0xFEFC)
 */
function hasArabic(text) {
    if (!text) return false;
    return /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFC]/.test(String(text));
}

/**
 * Reshape Arabic text using `js-arabic-reshaper`
 */
function reshapeArabic(text) {
    if (!text || !hasArabic(text)) return String(text || '');
    return reshape(String(text));
}

/**
 * Replaces Arabic currency words with their Latin ISO codes.
 * Used only when targeting a code page that cannot represent Arabic text
 * (CP437 / ASCII fallback), so the glyphs don't turn into mojibake.
 */
function cleanCurrency(str) {
    return String(str)
        .replace(/ر\.س/g, 'SAR')
        .replace(/د\.ك/g, 'KWD')
        .replace(/د\.إ/g, 'AED')
        .replace(/ج\.م/g, 'EGP')
        .replace(/د\.ب/g, 'BHD')
        .replace(/ر\.ع/g, 'OMR')
        .replace(/ر\.ق/g, 'QAR')
        .replace(/د\.ع/g, 'IQD')
        .replace(/د\.أ/g, 'JOD')
        .replace(/دينار/g, 'Dinar')
        .replace(/ريال/g, 'Rial')
        .replace(/درهم/g, 'Dirham');
}

/**
 * BiDi / Shaping Processor: reshapes Arabic glyphs into connected forms and
 * reorders the line for correct right-to-left reading on an LTR ESC/POS printer.
 * Pipeline: reshape (joined glyphs) -> BiDi reorder (visual order). This is the
 * standard order for ESC/POS / terminal rendering and is verified against mixed
 * Arabic+LTR strings (e.g. "قهوة عربية | Arabic Coffee").
 */
function processArabicLine(text) {
    if (!text || !hasArabic(text)) return String(text || '');

    const reshaped = reshape(String(text));
    try {
        const embeddingLevels = bidi.getEmbeddingLevels(reshaped);
        return bidi.getReorderedString(reshaped, embeddingLevels);
    } catch {
        // BiDi failure is rare; fall back to the shaped (still readable) form
        // rather than a blind reversal, which would corrupt mixed lines.
        return reshaped;
    }
}

