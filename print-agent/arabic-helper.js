/**
 * Encodes text into a Buffer based on the target ESC/POS encoding.
 * Supports CP864, CP1256, UTF-8, and CP437 with clean currency/character handling.
 */
function encodeEscPosString(text, encoding = 'cp864') {
    const enc = (encoding || 'cp864').toLowerCase().replace('-', '');

    // For CP437 (safe ASCII / emulator fallback mode):
    // Replace Arabic currency symbols cleanly so no mojibake is printed
    if (enc === 'cp437' || enc === 'ascii') {
        const clean = cleanCurrency(String(text));
        return iconv.encode(clean, 'cp437');
    }

    // Process Arabic text with shaping and BiDi reordering
    const processed = hasArabic(text) ? processArabicLine(text) : String(text);

    // CP864 (Standard ESC/POS Arabic Hardware Code Page)
    if (enc === 'cp864') {
        const bytes = [];
        // Normalize any composite presentation forms (NFKD) to ensure single-character lookup
        const normalized = processed.normalize('NFKD');
        for (let i = 0; i < normalized.length; i++) {
            const code = normalized.charCodeAt(i);
            if (CP864_BYTE_MAP[code]) {
                bytes.push(CP864_BYTE_MAP[code]);
            } else if (code < 128) {
                bytes.push(code);
            } else {
                const b = iconv.encode(normalized[i], 'cp864');
                for (const byte of b) bytes.push(byte);
            }
        }
        return Buffer.from(bytes);
    }

    // CP1256 (Windows Arabic)
    if (enc === 'cp1256') {
        let standardReversed = '';
        for (let i = 0; i < processed.length; i++) {
            const code = processed.charCodeAt(i);
            if (PRESENTATION_TO_STANDARD[code]) {
                standardReversed += String.fromCharCode(PRESENTATION_TO_STANDARD[code]);
            } else {
                standardReversed += processed[i];
            }
        }
        try {
            return iconv.encode(standardReversed, 'cp1256');
        } catch {
            return Buffer.from(standardReversed, 'utf8');
        }
    }

    // UTF-8 Mode
    return Buffer.from(processed, 'utf8');
}

/**
 * Clean currency string for thermal receipts: when the target code page cannot
 * represent Arabic (CP437 / ASCII fallback), replace Arabic currency words with
 * their Latin ISO codes so the glyphs don't turn into mojibake.
 */
function cleanCurrencyForCp437(val, encoding = 'cp864') {
    if (val === undefined || val === null) return '';
    const str = String(val);
    const enc = (encoding || 'cp864').toLowerCase().replace('-', '');
    if (enc === 'cp437' || enc === 'ascii') {
        return cleanCurrency(str);
    }
    return str;
}

